"""Publication review tests (G-8 for the web corpus).

The sample is an instrument: if it can drift between runs, or if a filled sheet can score against a label the
reviewer never typed, the agreement figure it produces is not evidence.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from gtaf.application.review_web import build_sample, read_labels, score, write_sample


def _rows() -> list[tuple[str, str, str, str, str, float]]:
    """Return a small labelled corpus: five from one source, two from the other."""
    return [
        ("p1", "imedi", "pro-government", "title one", "neutral", 0.8),
        ("p2", "imedi", "pro-government", "title two", "neutral", 0.7),
        ("p3", "imedi", "pro-government", "title three", "supportive", 0.9),
        ("p4", "imedi", "pro-government", "title four", "neutral", 0.6),
        ("p5", "imedi", "pro-government", "title five", "unclear", 0.5),
        ("p6", "tvpirveli", "opposition", "headline six", "critical", 0.7),
        ("p7", "tvpirveli", "opposition", "headline seven", "critical", 0.75),
    ]


def test_sample_is_deterministic_for_a_seed() -> None:
    """An auditable figure needs a sample that can be regenerated byte for byte."""
    first = build_sample(_rows(), {}, target="kobakhidze", size=4, seed=7)
    second = build_sample(_rows(), {}, target="kobakhidze", size=4, seed=7)

    assert [row.publication_id for row in first] == [row.publication_id for row in second]


def test_sample_differs_with_another_seed() -> None:
    """A seed that changes nothing is not a seed."""
    base = {row.publication_id for row in build_sample(_rows(), {}, target="t", size=4, seed=1)}
    other = {row.publication_id for row in build_sample(_rows(), {}, target="t", size=4, seed=2)}

    assert base != other or len(base) < 4


def test_sample_keeps_every_source_represented() -> None:
    """Proportional allocation alone would drop a small source from a 30-item check."""
    sample = build_sample(_rows(), {}, target="t", size=4, seed=3)

    assert {row.source_id for row in sample} == {"imedi", "tvpirveli"}


def test_sample_carries_the_stored_excerpt() -> None:
    """The reviewer must see the text the model saw, not a fresh fetch that may have changed."""
    sample = build_sample(
        _rows(), {"p1": "stored text"}, target="t", size=7, seed=1
    )

    row = next(item for item in sample if item.publication_id == "p1")
    assert row.excerpt == "stored text"


def test_write_then_read_round_trip(tmp_path: Path) -> None:
    """A filled sheet must read back exactly, and unfilled rows must be skipped, not guessed."""
    sample = build_sample(_rows(), {}, target="t", size=4, seed=5)
    path = tmp_path / "review.csv"
    write_sample(sample, path)

    text = path.read_text(encoding="utf-8")
    assert "human_label" in text.splitlines()[0]

    lines = text.splitlines()
    filled = []
    for line in lines[1:]:
        parts = line.split(",")
        parts[7] = "neutral"
        filled.append(",".join(parts))
    path.write_text("\n".join([lines[0], *filled]) + "\n", encoding="utf-8")

    human, model = read_labels(path)

    assert len(human) == len(sample)
    assert set(model.values()) <= {"neutral", "supportive", "unclear", "critical"}


def test_unfilled_sheet_yields_no_labels(tmp_path: Path) -> None:
    """An untouched sheet is not agreement data."""
    sample = build_sample(_rows(), {}, target="t", size=3, seed=5)
    path = tmp_path / "review.csv"
    write_sample(sample, path)

    human, _model = read_labels(path)

    assert human == {}


def test_invalid_label_is_rejected(tmp_path: Path) -> None:
    """A typo must fail loudly: silently dropping it would shrink the sample without saying so."""
    path = tmp_path / "review.csv"
    path.write_text(
        "publication_id,source,leaning,title,excerpt,model_label,confidence,human_label,note\n"
        "p1,imedi,pro-government,t,e,neutral,0.8,neutrak,\n",
        encoding="utf-8",
    )

    with pytest.raises(ValueError):
        read_labels(path)


def test_score_reports_kappa_and_the_sample_floor() -> None:
    """Agreement without kappa hides the dominance of one class; the floor stops a 5-item claim.

    The labels are deliberately mixed: with one class throughout, kappa is undefined by convention, so a
    perfect-agreement test on a single label would assert the degeneracy rather than the agreement.
    """
    human = {f"p{index}": "neutral" for index in range(5)}
    human.update({f"c{index}": "critical" for index in range(5)})
    model = dict(human)

    agreement, enough = score(human, model, min_items=30)

    assert agreement.rate == 1.0
    assert agreement.kappa == pytest.approx(1.0)
    assert enough is False
