"""Publication review tests (G-8 for the web corpus).

The sample is an instrument: if it can drift between runs, if it can score against a label the reviewer never
typed, or if it can pool two targets into one number, the agreement figure it produces is not evidence.
"""

from __future__ import annotations

import csv
from pathlib import Path

import pytest

from gtaf.application.review_web import build_sample, read_labels, score, write_sample


def _rows() -> list[tuple[str, str, str, str, str, float, str]]:
    """Return a small labelled corpus: five from one source, two from the other, two targets."""
    return [
        ("p1", "imedi", "pro-government", "title one", "neutral", 0.8, "kobakhidze"),
        ("p2", "imedi", "pro-government", "title two", "neutral", 0.7, "kobakhidze"),
        ("p3", "imedi", "pro-government", "title three", "supportive", 0.9, "kobakhidze"),
        ("p4", "imedi", "pro-government", "title four", "neutral", 0.6, "kobakhidze"),
        ("p5", "imedi", "pro-government", "title five", "unclear", 0.5, "kobakhidze"),
        ("p6", "tvpirveli", "opposition", "headline six", "critical", 0.7, "ivanishvili"),
        ("p7", "tvpirveli", "opposition", "headline seven", "critical", 0.75, "ivanishvili"),
    ]


def test_sample_is_deterministic_for_a_seed() -> None:
    """An auditable figure needs a sample that can be regenerated byte for byte."""
    first = build_sample(_rows(), {}, target="pooled", size=4, seed=7)
    second = build_sample(_rows(), {}, target="pooled", size=4, seed=7)

    assert [row.publication_id for row in first] == [row.publication_id for row in second]


def test_sample_differs_with_another_seed() -> None:
    """A seed that changes nothing is not a seed."""
    base = {row.publication_id for row in build_sample(_rows(), {}, target="t", size=4, seed=1)}
    other = {row.publication_id for row in build_sample(_rows(), {}, target="t", size=4, seed=2)}

    assert base != other or len(base) < 4


def test_sample_keeps_every_source_represented() -> None:
    """Proportional allocation alone would drop a small source from a 30-item check."""
    sample = build_sample(_rows(), {}, target="t", size=4, seed=3)

    assert {row.source_id for row in sample} == {"imedi", "tvpirveli"}


def test_each_row_keeps_its_own_target() -> None:
    """Measured 2026-11-26: a pooled sheet without per-row targets forced the reviewer to assume one target for
    two different questions, and the resulting agreement could not be interpreted."""
    sample = build_sample(_rows(), {}, target="pooled", size=7, seed=1)

    assert {row.target for row in sample} == {"kobakhidze", "ivanishvili"}


def test_sample_carries_the_stored_excerpt() -> None:
    """The reviewer must see the text the model saw, not a fresh fetch that may have changed."""
    sample = build_sample(_rows(), {"p1": "stored text"}, target="t", size=7, seed=1)

    row = next(item for item in sample if item.publication_id == "p1")
    assert row.excerpt == "stored text"


def test_write_then_read_round_trip(tmp_path: Path) -> None:
    """A filled sheet must read back exactly, with the target that belongs to each row."""
    sample = build_sample(_rows(), {}, target="pooled", size=4, seed=5)
    path = tmp_path / "review.csv"
    write_sample(sample, path)

    with path.open(encoding="utf-8", newline="") as handle:
        reader = csv.reader(handle)
        header = next(reader)
        body = list(reader)
    assert "target" in header
    human_column = header.index("human_label")
    for line in body:
        line[human_column] = "neutral"
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)
        writer.writerows(body)

    rows = read_labels(path)

    assert len(rows) == len(sample)
    assert {row[0] for row in rows} <= {"kobakhidze", "ivanishvili"}
    assert all(row[2] == "neutral" for row in rows)


def test_unfilled_sheet_yields_no_labels(tmp_path: Path) -> None:
    """An untouched sheet is not agreement data."""
    sample = build_sample(_rows(), {}, target="t", size=3, seed=5)
    path = tmp_path / "review.csv"
    write_sample(sample, path)

    assert read_labels(path) == []


def test_sheet_without_a_target_column_is_refused(tmp_path: Path) -> None:
    """A pooled sheet with no target cannot be scored; failing loudly beats one number for two questions."""
    path = tmp_path / "review.csv"
    path.write_text(
        "publication_id,source,leaning,title,excerpt,model_label,confidence,human_label,note\n"
        "p1,imedi,pro-government,t,e,neutral,0.8,neutral,\n",
        encoding="utf-8",
    )

    with pytest.raises(ValueError):
        read_labels(path)


def test_invalid_label_is_rejected(tmp_path: Path) -> None:
    """A typo must fail loudly: silently dropping it would shrink the sample without saying so."""
    path = tmp_path / "review.csv"
    path.write_text(
        "publication_id,target,source,leaning,title,excerpt,model_label,confidence,human_label,note\n"
        "p1,kobakhidze,imedi,pro-government,t,e,neutral,0.8,neutrak,\n",
        encoding="utf-8",
    )

    with pytest.raises(ValueError):
        read_labels(path)


def test_score_reports_kappa_per_target_and_the_floor() -> None:
    """A mixed sheet answered two questions; averaging them would hide which one failed.

    The labels are deliberately mixed: with one class throughout, kappa is undefined by convention, so a
    perfect-agreement test on a single label would assert the degeneracy rather than the agreement.
    """
    rows: list[tuple[str, str, str, str]] = []
    for index in range(5):
        rows.append(("kobakhidze", f"k{index}", "neutral", "neutral"))
    for index in range(5):
        rows.append(("kobakhidze", f"c{index}", "critical", "critical"))
    rows.append(("ivanishvili", "i1", "critical", "neutral"))

    results = score(rows, min_items=30)

    agreement, enough = results["kobakhidze"]
    assert agreement.rate == 1.0
    assert agreement.kappa == pytest.approx(1.0)
    assert enough is False
    ivanishvili, _ = results["ivanishvili"]
    assert ivanishvili.n == 1
    assert ivanishvili.rate == 0.0
